/**
 * Agent markdown rendering for the OpenCode V2 port (S3a).
 *
 * V2 has no `agent.transform().add()`: an agent exists only if it is a markdown file (or a config
 * entry). This module turns a V1 `AgentConfig` — the exact object the V1 factories produce — into
 * the frontmatter V2's markdown loader understands. Nothing here authors prompt text; the body is
 * always the factory's `prompt`, so the two harnesses cannot drift.
 *
 * Field support was measured against OpenCode V2.1.4 by writing each key and reading `/api/agent`
 * back (see `docs`/the S3a report):
 *
 *   description, mode, hidden, color, steps        → first-class `Agent.Info` fields
 *   model ("provider/model"), variant              → `Agent.Info.model` (+ `.variant`)
 *   temperature, top_p, maxTokens, reasoningEffort,
 *   textVerbosity                                  → `Agent.Info.request.body.*` (provider body)
 *   permission {tool: allow|deny|ask}              → `Agent.Info.permissions[]`
 *                                                   (V2 maps write→edit and bash→shell itself)
 *   tools {tool: boolean}                          → `Agent.Info.permissions[]` (deny/allow)
 *
 * Keys that are NOT emitted because V2 would ignore them silently:
 *   reasoning (the V1 alias of `variant`), prompt (the body is the prompt), disable (we delete the
 *   file instead), prompt_append / skills / category (baked into the prompt by the factory).
 */
import type { AgentConfig } from "@opencode-ai/sdk"

/** Marks a file as ours; the loader treats `#` lines inside frontmatter as YAML comments. */
export const AGENT_GENERATED_COMMENT =
  "# generated by oh-my-openagent v2; model-specific sections applied at runtime"

/** `<prefix> <agent name>` identifies a file this plugin may delete. */
export const AGENT_MARKER_PREFIX = "# omo-v2-agent:"

export function agentMarkerLine(name: string): string {
  return `${AGENT_MARKER_PREFIX} ${name}`
}

/** True only for markdown this plugin wrote (never a user-authored file with the same name). */
export function isManagedAgentMarkdown(content: string, name?: string): boolean {
  // The marker lives in the frontmatter block, so only the first few lines can carry it.
  const head = content.split("\n", 8).map((line) => line.trim())
  return name === undefined
    ? head.some((line) => line.startsWith(AGENT_MARKER_PREFIX))
    : head.includes(agentMarkerLine(name))
}

export type RenderAgentMarkdownOptions = {
  readonly name: string
  /**
   * `provider/model` that the host can actually resolve. When omitted the file carries no model,
   * and model-coupled keys (variant / reasoningEffort / textVerbosity) are dropped with it: they
   * only make sense next to the model family the factory picked them for.
   */
  readonly model?: string
  /** Keys the renderer could not express; surfaced by the caller as warnings. */
  readonly onUnsupported?: (key: string, reason: string) => void
}

type PermissionValue = string | Record<string, string>

function quote(value: string): string {
  // JSON string literals are valid YAML double-quoted scalars (and escape tabs/newlines).
  return JSON.stringify(value)
}

function scalar(value: string | number | boolean): string {
  return typeof value === "string" ? quote(value) : String(value)
}

const PERMISSION_EFFECTS = new Set(["allow", "deny", "ask"])

/**
 * Flattens the V1 `permission` map into the flat `action: effect` pairs V2 accepts.
 * Nested values (`bash: { "git *": "deny" }`) have no V2 equivalent in a markdown file: V2 stores
 * one effect per action, so they are reported instead of silently degrading to "allow".
 */
export function flattenPermissions(
  config: AgentConfig,
  onUnsupported?: (key: string, reason: string) => void,
): Array<readonly [string, string]> {
  const entries: Array<readonly [string, string]> = []
  const seen = new Set<string>()

  const push = (key: string, value: unknown): void => {
    if (typeof value !== "string" || !PERMISSION_EFFECTS.has(value)) {
      onUnsupported?.(key, "nested or non allow|deny|ask permission value has no V2 markdown equivalent")
      return
    }
    if (seen.has(key)) return
    seen.add(key)
    entries.push([key, value])
  }

  const permission = (config as { permission?: Record<string, PermissionValue> }).permission
  for (const [key, value] of Object.entries(permission ?? {})) push(key, value)

  // V1 `tools: { grep: false }` is the same restriction as `permission: { grep: "deny" }`.
  const tools = (config as { tools?: Record<string, boolean> }).tools
  for (const [key, value] of Object.entries(tools ?? {})) push(key, value ? "allow" : "deny")

  return entries
}

/** Renders one agent as the markdown file OpenCode V2 discovers. Deterministic: same input, same bytes. */
export function renderAgentMarkdown(config: AgentConfig, options: RenderAgentMarkdownOptions): string {
  const { name, model, onUnsupported } = options
  const record = config as Record<string, unknown>
  const description = typeof record.description === "string" && record.description.length > 0
    ? record.description
    : `Oh My OpenAgent built-in agent (${name})`
  const mode = typeof record.mode === "string" && record.mode.length > 0 ? record.mode : "subagent"

  const lines: string[] = ["---", AGENT_GENERATED_COMMENT, agentMarkerLine(name)]
  lines.push(`description: ${quote(description)}`)
  lines.push(`mode: ${mode}`)

  if (model) {
    lines.push(`model: ${quote(model)}`)
    if (typeof record.variant === "string" && record.variant.length > 0) lines.push(`variant: ${quote(record.variant)}`)
  } else {
    for (const key of ["variant", "reasoningEffort", "textVerbosity"]) {
      if (record[key] !== undefined) onUnsupported?.(key, "model-coupled key dropped because no V2-resolvable model was written")
    }
  }

  // Provider body knobs: V2 forwards unknown frontmatter keys into `Agent.Info.request.body`.
  for (const key of ["temperature", "top_p", "maxTokens"] as const) {
    const value = record[key]
    if (typeof value === "number") lines.push(`${key}: ${scalar(value)}`)
  }
  if (model) {
    for (const key of ["reasoningEffort", "textVerbosity"] as const) {
      const value = record[key]
      if (typeof value === "string" && value.length > 0) lines.push(`${key}: ${quote(value)}`)
    }
  }

  if (record.hidden === true) lines.push("hidden: true")
  if (typeof record.color === "string" && record.color.length > 0) lines.push(`color: ${quote(record.color)}`)

  const permissions = flattenPermissions(config, onUnsupported)
  if (permissions.length > 0) {
    lines.push("permission:")
    for (const [key, effect] of permissions) lines.push(`  ${quote(key)}: ${effect}`)
  }

  lines.push("---", "")
  const prompt = typeof record.prompt === "string" ? record.prompt : ""
  lines.push(prompt.length > 0 ? prompt.replace(/\s+$/, "") : `# ${name}`)
  lines.push("")
  return lines.join("\n")
}
